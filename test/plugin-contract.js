var test = require("node:test")
var assert = require("assert")
var fs = require("fs")

test("plugin is one-finger swipe only", function () {
  var manifest = JSON.parse(fs.readFileSync("manifest.json", "utf8"))
  assert.strictEqual(manifest.id, "rainan16.workspace-touch-swipe")
  assert.strictEqual(manifest.homepage, "https://github.com/rainan16/omarchy-workspace-touch-swipe")
  assert.ok(manifest.description.indexOf("One-finger") !== -1)
  assert.ok(!fs.existsSync("touch-gesture-daemon.c"))
  assert.ok(!fs.existsSync("setup-two-finger.sh"))
  assert.ok(!fs.existsSync("uninstall-two-finger.sh"))
  var service = fs.readFileSync("Service.qml", "utf8")
  assert.ok(service.indexOf("Process") === -1)
  assert.ok(service.indexOf("twoFinger") === -1)
  var overlay = fs.readFileSync("Overlay.qml", "utf8")
  assert.ok(overlay.indexOf("twoFinger") === -1)
  assert.ok(overlay.indexOf("mouseEnabled: false") !== -1)
  assert.ok(overlay.indexOf("edgeHitWidth") !== -1)
  assert.ok(overlay.indexOf("leftHitMask") !== -1)
  assert.ok(overlay.indexOf("rightHitMask") !== -1)
  var model = fs.readFileSync("GestureModel.js", "utf8")
  assert.ok(model.indexOf("twoFinger") === -1)
  var readme = fs.readFileSync("README.md", "utf8")
  assert.ok(readme.indexOf("omarchy plugin add https://github.com/rainan16/omarchy-workspace-touch-swipe.git --enable") !== -1)
  assert.ok(readme.indexOf("## Two-finger swipes") === -1)
  assert.ok(readme.indexOf("setup-two-finger.sh") === -1)
  assert.ok(readme.indexOf("twoFinger") === -1)
  assert.ok(readme.indexOf("usermod") === -1)
})
